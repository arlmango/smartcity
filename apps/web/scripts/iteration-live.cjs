const { chromium } = require('@playwright/test');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1440,height:900},locale:'ru-RU'});
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:3208');
 await page.getByRole('button',{name:/Демо-точка/}).click();
 await page.getByRole('button',{name:'60 мин',exact:true}).click();
 await page.getByLabel('Что хочется').fill('Хочу погулять и посмотреть интересные места');
 const start=Date.now();
 await page.getByRole('button',{name:'Подобрать прогулку',exact:true}).click();
 await page.getByTestId('rec-card').first().waitFor({timeout:210000});
 const firstCardsMs=Date.now()-start;
 console.log(JSON.stringify({firstCardsMs}));
 await page.getByRole('region',{name:'Сравнить варианты'}).scrollIntoViewIfNeeded();
 await page.screenshot({path:'../../artifacts/iteration/live-preliminary-desktop.png'});
 await page.getByText('Места уже найдены поиском по базе — ИИ ещё готовит объяснения.').waitFor({state:'hidden',timeout:210000});
 const finalMs=Date.now()-start;
 await page.getByRole('region',{name:'Сравнить варианты'}).scrollIntoViewIfNeeded();
 await page.screenshot({path:'../../artifacts/iteration/live-final-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Список',exact:true}).click();
 await page.getByRole('region',{name:'Сравнить варианты'}).scrollIntoViewIfNeeded();
 await page.screenshot({path:'../../artifacts/iteration/live-final-mobile.png'});
 const evidence={firstCardsMs,finalMs,errors,comparison:await page.getByRole('region',{name:'Сравнить варианты'}).innerText(),heading:await page.locator('#summary-h').innerText()};
 fs.writeFileSync('../../artifacts/iteration/live.json',JSON.stringify(evidence,null,2));
 console.log(JSON.stringify(evidence));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
