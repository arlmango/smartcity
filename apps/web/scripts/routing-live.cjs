const { chromium } = require('@playwright/test');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1440,height:900},locale:'ru-RU'});
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:3208');
 await page.getByRole('button',{name:/Демо-точка/}).click();
 await page.getByRole('button',{name:'60 мин',exact:true}).click();
 await page.getByLabel('Что хочется').fill('Хочу погулять и посмотреть интересные места');
 const start=Date.now();
 await page.getByRole('button',{name:'Подобрать прогулку',exact:true}).click();
 await page.getByTestId('rec-card').first().waitFor({timeout:210000});
 const firstCardsMs=Date.now()-start;
 await page.getByTestId('route-legend').waitFor({timeout:10000});
 console.log(JSON.stringify({firstCardsMs,legend:await page.getByTestId('route-legend').innerText()}));
 await page.waitForFunction(()=>window.__smartcityMap && !window.__smartcityMap.isMoving());
 await page.getByRole('region',{name:'Сравнить варианты'}).scrollIntoViewIfNeeded();
 await page.screenshot({path:'../../artifacts/routing-pilot/live-preliminary-desktop.png'});
 const preliminary = await page.evaluate(async()=>({selected:document.querySelector('[data-testid="rec-card"][aria-current="true"]')?.getAttribute('data-place-id'),route:await window.__smartcityMap?.getSource('walking-route')?.getData()}));
 await page.getByText('Места уже найдены поиском по базе — ИИ ещё готовит объяснения.').waitFor({state:'hidden',timeout:210000});
 const finalMs=Date.now()-start;
 const final = await page.evaluate(async()=>({selected:document.querySelector('[data-testid="rec-card"][aria-current="true"]')?.getAttribute('data-place-id'),route:await window.__smartcityMap?.getSource('walking-route')?.getData()}));
 await page.screenshot({path:'../../artifacts/routing-pilot/live-final-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Карта',exact:true}).click();
 await page.waitForFunction(()=>!window.__smartcityMap.isMoving());
 await page.screenshot({path:'../../artifacts/routing-pilot/live-mobile-map.png'});
 await page.getByRole('button',{name:'Список',exact:true}).click();
 await page.getByRole('region',{name:'Сравнить варианты'}).scrollIntoViewIfNeeded();
 await page.screenshot({path:'../../artifacts/routing-pilot/live-mobile-cards.png'});
 const evidence={firstCardsMs,finalMs,errors,preliminary,final,comparison:await page.getByRole('region',{name:'Сравнить варианты'}).innerText(),heading:await page.locator('#summary-h').innerText(),cards:await page.getByTestId('rec-card').allTextContents()};
 await page.getByRole('button',{name:'Начать заново',exact:true}).click();
 evidence.reset={endpoints:await page.getByTestId('route-endpoint').count(),legends:await page.getByTestId('route-legend').count()};
 fs.writeFileSync('../../artifacts/routing-pilot/live.json',JSON.stringify(evidence,null,2));
 console.log(JSON.stringify({firstCardsMs,finalMs,errors,reset:evidence.reset,comparison:evidence.comparison}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
